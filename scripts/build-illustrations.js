/**
 * Bundles assets/illustrations/*.svg into lib/illustrations.ts (XML strings for
 * react-native-svg's SvgXml). Adds a viewBox so every illustration scales cleanly.
 *   node scripts/build-illustrations.js
 */
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'assets', 'illustrations');
const out = path.join(__dirname, '..', 'lib', 'illustrations.ts');
const entries = [];
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.svg')).sort()) {
  let svg = fs.readFileSync(path.join(dir, f), 'utf8').replace(/<\?xml[^>]*>/, '').replace(/<!--[\s\S]*?-->/g, '').trim();
  const w = +(svg.match(/width="([\d.]+)"/) || [])[1];
  const h = +(svg.match(/height="([\d.]+)"/) || [])[1];
  if (!/viewBox=/.test(svg)) svg = svg.replace('<svg ', `<svg viewBox="0 0 ${w} ${h}" `);
  svg = svg.replace(/\s+/g, ' ');
  entries.push({ name: path.basename(f, '.svg'), svg, ratio: +(w / h).toFixed(4) });
}
const body = entries.map((e) => `  ${e.name}: { ratio: ${e.ratio}, xml: ${JSON.stringify(e.svg)} },`).join('\n');
fs.writeFileSync(
  out,
  `// Generated by scripts/build-illustrations.js from assets/illustrations/*.svg — do not edit.\n` +
    `// Flat illustrations drawn in Gemini, vectorised with scripts/vectorize.py (transparent background).\n` +
    `export const ILLUSTRATIONS = {\n${body}\n} as const;\n\nexport type IllustrationName = keyof typeof ILLUSTRATIONS;\n`,
);
console.log('wrote', path.relative(process.cwd(), out), entries.map((e) => `${e.name}(${(e.svg.length / 1024).toFixed(0)}KB)`).join(' '));
